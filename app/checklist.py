IP_RE = re.compile(r"\bIP\s?\d{2}", re.IGNORECASE)


def detect_type(name: str, hint: str = "") -> str:
    text = f"{hint} {name}".lower()
    for device_type, pattern in TYPE_PATTERNS:
        if re.search(pattern, text):
            return device_type
    return "прибор"


def _covered(item: str, spec_keys: list[str], specs_text: str) -> bool:
    for synonym in SYNONYMS.get(item, [item.lower()]):
        if any(synonym in key for key in spec_keys):
            return True
    if item == "Степень защиты" and IP_RE.search(specs_text):
        return True
    return False


def missing_recommended(device_type: str, specs: dict[str, str]) -> list[str]:
    """Характеристики из чек-листа типа, которых нет среди заполненных specs."""
    keys = [k.lower() for k in specs]
    specs_text = " ".join(f"{k} {v}" for k, v in specs.items())
    return [item for item in CHECKLISTS[device_type] if not _covered(item, keys, specs_text)]
