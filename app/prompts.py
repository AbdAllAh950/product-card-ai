SPARSE_NOTE = (
    "Данных о товаре мало. Опиши только то, что есть, даже если описание получится короче "
    f"{DESCRIPTION_MIN} символов, — код отметит это для контент-менеджера. Не добавляй общих фраз "
    "о назначении приборов этого типа."
)


def build_user_prompt(product: Product) -> str:
    facts = json.dumps(product.facts(), ensure_ascii=False, indent=2)
    missing = ", ".join(product.missing_specs) if product.missing_specs else "—"
    sparse = f"\n{SPARSE_NOTE}\n" if product.is_sparse else ""
    return f"""ДАННЫЕ О ТОВАРЕ (единственный источник фактов):
```json
{facts}
```
Тип прибора: {product.device_type}.
Обычно важные для этого типа характеристики, которых НЕТ в данных: {missing}. Не упоминай их значения.
{sparse}
Сформируй JSON строго по схеме:
{OUTPUT_SCHEMA}

Только если в данных совсем нет сведений о применении, в for_whom напиши «Область применения в исходных данных не указана»."""


VERIFY_SYSTEM_PROMPT = """Ты — фактчекер карточек товаров КИП. Сверяешь утверждения из карточки с данными о товаре.

Утверждение ПОДТВЕРЖДЕНО, если оно прямо следует из данных: перефразирование, объединение фактов \
и очевидное назначение прибора («измерение давления» для манометра) допустимы.
Утверждение НЕ ПОДТВЕРЖДЕНО, если добавляет свойство, оценку, следствие, область применения, \
совместимость или преимущество, которых в данных нет. Пример: «мембрана устойчива к коррозии», \
если про коррозию в данных ничего не сказано.

Ответ — только JSON: {"unsupported": [{"id": <номер>, "reason": "что именно не подтверждается"}]}. \
Если всё подтверждено — {"unsupported": []}."""


def build_verify_prompt(product: Product, statements: list[str]) -> str:
    facts = json.dumps(product.facts(), ensure_ascii=False, indent=2)
    listed = "\n".join(f"{i}. {s}" for i, s in enumerate(statements, start=1))
    return f"""ДАННЫЕ О ТОВАРЕ:
```json
{facts}
```

УТВЕРЖДЕНИЯ ИЗ КАРТОЧКИ:
{listed}

Найди утверждения, которые не подтверждаются данными."""


def build_repair_prompt(problems: list[str]) -> str:
    listed = "\n".join(f"- {p}" for p in problems)
    return f"""В ответе найдены проблемы:
{listed}

Исправь только их и верни полный JSON по той же схеме. Факты, числа и термины — только из «ДАННЫХ О ТОВАРЕ»; \
если для исправления не хватает фактов, лучше убери фразу, чем добавляй новое."""
